#!/usr/bin/env node
import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import { readFile, open, rename, unlink } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { syncDirectory } from "../src/platform/owner-only-filesystem.js";

const SCRIPT_FILE = fileURLToPath(import.meta.url);
export const CODEX_BROWSER_MIRROR_FILE = fileURLToPath(
  new URL("../apps/web/public/codex-catalog.generated.js", import.meta.url),
);

export async function buildCodexBrowserMirror() {
  const digest = createHash("sha256");
  const sections = [];
  for (const name of ["plans.js", "model-catalog.js"]) {
    const path = `packages/codex-catalog/src/${name}`;
    const source = await readFile(new URL(`../${path}`, import.meta.url), "utf8");
    assert.doesNotMatch(source, /^\s*(?:import|export\s+\{)/mu,
      "Review browser catalog imports before extending the mirror");
    digest.update(path).update("\0").update(source).update("\0");
    sections.push(`// ---- canonical: ${path} ----\n${source.trimEnd()}`);
  }
  return [
    "// @generated by scripts/generate-codex-browser-mirror.js",
    "// Do not edit this browser-served mirror directly.",
    `// Canonical SHA-256: ${digest.digest("hex")}`, "", ...sections, "",
  ].join("\n");
}

export async function checkCodexBrowserMirror() {
  assert.equal(await readFile(CODEX_BROWSER_MIRROR_FILE, "utf8"),
    await buildCodexBrowserMirror(), "Codex browser catalog is stale; regenerate it");
}

async function main() {
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 1 && args[0] === "--check"));
  if (args[0] === "--check") return checkCodexBrowserMirror();
  const temporary = `${CODEX_BROWSER_MIRROR_FILE}.${randomUUID()}.tmp`;
  try {
    const handle = await open(temporary, "wx", 0o644);
    try {
      await handle.writeFile(await buildCodexBrowserMirror(), "utf8");
      await handle.sync();
    } finally { await handle.close(); }
    await rename(temporary, CODEX_BROWSER_MIRROR_FILE);
    await syncDirectory(dirname(CODEX_BROWSER_MIRROR_FILE));
  } finally {
    await unlink(temporary).catch((error) => { if (error.code !== "ENOENT") throw error; });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_FILE) {
  main().catch((error) => { console.error(error); process.exitCode = 1; });
}
