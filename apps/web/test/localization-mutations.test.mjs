import assert from "node:assert/strict";
import test from "node:test";

import {
  createBrowserLocalization,
  translateLegacyText,
} from "../public/localization.js";

// A queued DOM harness: appending nodes and writing text produce observer
// records automatically, including records caused by the localizer itself.
// This exercises mutation delivery and settling rather than source patterns.
function mutationDocument() {
  let activeObserver = null;
  let writes = 0;
  const queue = [];
  const filter = { SHOW_TEXT: 4, FILTER_ACCEPT: 1, FILTER_REJECT: 2 };
  const notify = (record) => {
    if (activeObserver && record.target.isConnected) queue.push(record);
  };
  class Element {
    constructor(tagName = "div", attributes = {}) {
      this.nodeType = 1;
      this.tagName = tagName.toUpperCase();
      this.attributes = attributes;
      this.children = [];
      this.dataset = {};
      this.parentElement = null;
      this.ownerDocument = documentRef;
    }
    get isConnected() {
      return this === documentRef.documentElement || this.parentElement?.isConnected === true;
    }
    matches(selector) {
      return selector.split(",").some((part) =>
        Object.hasOwn(this.attributes, part.trim().slice(1, -1)));
    }
    closest(selector) {
      return this.matches(selector) ? this : this.parentElement?.closest(selector) ?? null;
    }
    querySelectorAll(selector) {
      return this.children.filter((node) => node.nodeType === 1)
        .flatMap((node) => [
          ...(node.matches(selector) ? [node] : []),
          ...node.querySelectorAll(selector),
        ]);
    }
    append(node) {
      node.parentElement = this;
      this.children.push(node);
      notify({ type: "childList", target: this, addedNodes: [node] });
    }
  }
  class Text {
    constructor(value) {
      this.nodeType = 3;
      this.value = value;
      this.parentElement = null;
      this.ownerDocument = documentRef;
    }
    get isConnected() { return this.parentElement?.isConnected === true; }
    get nodeValue() { return this.value; }
    set nodeValue(value) {
      this.value = value;
      writes += 1;
      notify({ type: "characterData", target: this });
    }
  }
  const documentRef = {
    defaultView: { NodeFilter: filter },
    querySelectorAll(selector) { return this.documentElement.querySelectorAll(selector); },
    createTreeWalker(root, _kind, { acceptNode }) {
      const nodes = [];
      const visit = (node) => {
        for (const child of node.children ?? []) {
          if (child.nodeType === 3 && acceptNode(child) === filter.FILTER_ACCEPT) nodes.push(child);
          else if (child.nodeType === 1) visit(child);
        }
      };
      visit(root);
      let index = 0;
      return {
        currentNode: null,
        nextNode() { this.currentNode = nodes[index++]; return Boolean(this.currentNode); },
      };
    },
  };
  documentRef.documentElement = new Element("html");
  const body = new Element("body", { "data-i18n-root": "" });
  const legacy = new Element("section", { "data-i18n-legacy-root": "" });
  documentRef.documentElement.append(body);
  body.append(legacy);
  const windowRef = {
    navigator: { languages: ["zh-CN"] },
    MutationObserver: class {
      constructor(callback) { this.callback = callback; }
      observe() { activeObserver = this; }
    },
  };
  return {
    body, legacy, documentRef, windowRef,
    element: (attributes) => new Element("span", attributes),
    text: (value) => new Text(value),
    writes: () => writes,
    flush() {
      let deliveries = 0;
      while (queue.length) {
        assert.ok(++deliveries <= 10, "localization mutations must settle without a redraw loop");
        activeObserver.callback(queue.splice(0));
      }
      return deliveries;
    },
  };
}

test("inserted legacy product text translates on its first mutation and survives locale switches", () => {
  const dom = mutationDocument();
  const localizer = createBrowserLocalization(dom);
  const product = dom.element();
  const nested = dom.text("First-time setup");
  product.append(nested);
  dom.legacy.append(product);
  const direct = dom.text("Ready");
  dom.legacy.append(direct);
  const skipped = dom.element({ "data-i18n-skip": "" });
  const userText = dom.text("Ready");
  skipped.append(userText);
  dom.legacy.append(skipped);
  const outside = dom.text("Ready");
  dom.body.append(outside);

  // Deliver only the insertion batch first: translation must not depend on
  // the later characterData records generated by these translation writes.
  const deliveries = dom.flush();
  assert.equal(nested.nodeValue, translateLegacyText("First-time setup", "zh-Hans"));
  assert.equal(direct.nodeValue, translateLegacyText("Ready", "zh-Hans"));
  assert.equal(userText.nodeValue, "Ready");
  assert.equal(outside.nodeValue, "Ready");
  assert.equal(dom.writes(), 2);
  assert.ok(deliveries <= 2, "translation must settle after insertion and its own text changes");

  for (const locale of ["en-US", "es", "zh-Hans"]) {
    localizer.setLanguagePreference(locale, { announce: false });
    assert.equal(nested.nodeValue, translateLegacyText("First-time setup", locale));
    assert.equal(direct.nodeValue, translateLegacyText("Ready", locale));
    assert.equal(userText.nodeValue, "Ready");
    assert.equal(outside.nodeValue, "Ready");
    const writes = dom.writes();
    assert.equal(dom.flush(), 1);
    assert.equal(dom.writes(), writes, "observer delivery must not rewrite settled translations");
  }
  localizer.localizeTree();
  assert.equal(dom.flush(), 0);
  assert.equal(dom.writes(), 8);
});
